#!/usr/bin/env python3
"""Build the GUACESP FAT payload: the SM8150 kernel plus the device's Apple Device Tree.

The device comes from board.toml ([board] name); the kernel is
inputs/<name>/kernel.macho (from the kernel workflow); the ADT is generated by
board.toml [payload.adt] tool (scripts/make-<name>-adt.py) from the iPhone X
(D22AP) base tree and the device profile in scripts/devices.py.

On andromeda the payload must be small: the ABL loads the ramdisk at
0x80800000 and the "Kernel" region of the memory map ends at 0x82A00000, so
board.toml asks for 34 MiB. UniXNU's mformat call lets mtools pick the cluster
size, which for so small a volume can give fewer than the 65525 clusters FAT32
needs (the firmware's FatDxe then refuses it); one sector per cluster is forced
here, and the result is checked.
"""
import os
import struct
import sys
import tomllib
import types
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "unixnu" / "scripts"))
sys.path.insert(0, str(ROOT / "scripts"))

from unixnu import payload  # noqa: E402
from unixnu.util import run, tool  # noqa: E402
from tree import assemble  # noqa: E402

board = tomllib.loads((ROOT / "board.toml").read_text())
NAME = board["board"]["name"]
WORK = ROOT / "out" / NAME
TREE = assemble(WORK, ROOT / "unixnu", ROOT)
LOGS = WORK / "logs"
LOGS.mkdir(parents=True, exist_ok=True)
KERNEL = Path(os.environ.get("KERNEL", ROOT / "inputs" / NAME / "kernel.macho"))
if not KERNEL.is_file():
    raise SystemExit(f"payload: no kernel at {KERNEL} (run the kernel-{NAME} workflow and download its artifact)")


def write_volume(stage, image, label, size_mib):
    """payload.write_volume, with one 512-byte sector per cluster and a FAT32 check."""
    for tool_name in ("mformat", "mcopy"):
        tool(tool_name)
    image.unlink(missing_ok=True)
    env = dict(os.environ, MTOOLS_SKIP_CHECK="1", TZ="UTC")
    sectors = size_mib * 2048
    run(["mformat", "-C", "-F", "-c", "1", "-T", str(sectors), "-v", label, "-N", "53484e47",
         "-i", image, "::"], env=env, capture=True)
    for entry in sorted(stage.iterdir()):
        run(["mcopy", "-i", image, "-s", "-Q", "-m", entry, "::/"], env=env, capture=True)
    boot = Path(image).read_bytes()[:512]
    bps, spc = struct.unpack_from("<HB", boot, 11)
    reserved = struct.unpack_from("<H", boot, 14)[0]
    total, fat_size = struct.unpack_from("<II", boot, 32)
    clusters = (total - reserved - 2 * fat_size) // spc
    if boot[510:512] != b"\x55\xaa" or boot[82:90] != b"FAT32   " or clusters < 65525:
        raise SystemExit(f"payload: {image} is not a valid FAT32 ({clusters} clusters)")
    print(f"payload: {image} {size_mib} MiB FAT32, {clusters} clusters, label {label}")


payload.write_volume = write_volume

ctx = types.SimpleNamespace(
    board=board,
    tree=TREE,
    work=WORK,
    logs=LOGS,
    uefi=ROOT / "uefi",
    args=types.SimpleNamespace(
        kernel=KERNEL,
        kernel_arg=None,
        trust_cache=None,
        owner_trust_cache=None,
        data_ramdisk=None,
        skip_setup=False,
        unique_chip_id="0x5357454554000001",
    ),
)
payload.build(ctx)
